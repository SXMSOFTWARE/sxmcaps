export type I18nDict = (typeof TRANSLATIONS)[ResolvedLanguage];

interface I18nContextValue {
  pref: LanguagePreference;
  lang: ResolvedLanguage;
  t: I18nDict;
}

const I18nContext = createContext<I18nContextValue>({
  pref: 'auto',
  lang: detectSystemLanguage(),
  t: TRANSLATIONS[detectSystemLanguage()],
});

export const I18nProvider: React.FC<{
  preference?: string;
  children: React.ReactNode;
}> = ({ preference, children }) => {
  const pref: LanguagePreference =
    preference === 'tr' || preference === 'en' ? preference : 'auto';
  const lang = resolveLanguage(pref);
  return (
    <I18nContext.Provider value={{ pref, lang, t: TRANSLATIONS[lang] }}>
      {children}
    </I18nContext.Provider>
  );
};

export function useI18n() {
  return useContext(I18nContext);
}
