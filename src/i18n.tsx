import React, { createContext, useContext } from 'react';

export type LanguagePreference = 'auto' | 'tr' | 'en';
export type ResolvedLanguage = 'tr' | 'en';

export function detectSystemLanguage(): ResolvedLanguage {
  if (typeof navigator === 'undefined') return 'en';
  const candidates =
    Array.isArray(navigator.languages) && navigator.languages.length > 0
      ? navigator.languages
      : [navigator.language || 'en'];
  const primary = (candidates[0] || 'en').toLowerCase();
  return primary.startsWith('tr') ? 'tr' : 'en';
}

export function resolveLanguage(pref?: string | null): ResolvedLanguage {
  if (pref === 'tr') return 'tr';
  if (pref === 'en') return 'en';
  return detectSystemLanguage();
}

