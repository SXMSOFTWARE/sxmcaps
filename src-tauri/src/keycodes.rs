#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MouseButtonKind {
    Left,
    Right,
    Middle,
    Side,
    Extra,
}

impl MouseButtonKind {
    pub fn as_web_code(self) -> &'static str {
        match self {
            MouseButtonKind::Left => "MouseLeft",
            MouseButtonKind::Right => "MouseRight",
            MouseButtonKind::Middle => "MouseMiddle",
            MouseButtonKind::Side => "MouseSide",
            MouseButtonKind::Extra => "MouseExtra",
        }
    }
}

pub fn evdev_to_mouse_button(code: u16) -> Option<MouseButtonKind> {
    match code {
        0x110 => Some(MouseButtonKind::Left),   // BTN_LEFT
        0x111 => Some(MouseButtonKind::Right),  // BTN_RIGHT
        0x112 => Some(MouseButtonKind::Middle), // BTN_MIDDLE
        0x113 => Some(MouseButtonKind::Side),   // BTN_SIDE (Thumb Back)
        0x114 => Some(MouseButtonKind::Extra),  // BTN_EXTRA (Thumb Forward)
        _ => None,
    }
}

