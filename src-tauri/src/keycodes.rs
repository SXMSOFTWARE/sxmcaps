pub fn categorize_web_code(web_code: &str) -> KeyCategory {
    match web_code {
        "Space" => KeyCategory::Space,
        "Enter" | "Backspace" | "NumpadEnter" => KeyCategory::Enter,
        "ShiftLeft" | "ShiftRight" | "ControlLeft" | "ControlRight" | "AltLeft" | "AltRight"
        | "MetaLeft" | "MetaRight" | "Tab" | "CapsLock" => KeyCategory::Modifier,
        _ => KeyCategory::Normal,
    }
}

/// Subtle stereo panning (-0.42 left side .. +0.42 right side) for spatial keyboard feel
pub fn web_code_pan(web_code: &str) -> f32 {
    match web_code {
        "Escape" | "Backquote" | "Tab" | "CapsLock" | "ShiftLeft" | "ControlLeft" | "MetaLeft"
        | "Digit1" | "KeyQ" | "KeyA" | "KeyZ" | "F1" => -0.40,
        "Digit2" | "KeyW" | "KeyS" | "KeyX" | "AltLeft" | "F2" => -0.30,
        "Digit3" | "KeyE" | "KeyD" | "KeyC" | "F3" => -0.20,
        "Digit4" | "KeyR" | "KeyF" | "KeyV" | "F4" => -0.12,
        "Digit5" | "KeyT" | "KeyG" | "KeyB" | "F5" => -0.05,
        "Space" | "Digit6" | "KeyY" | "KeyH" | "KeyN" | "F6" => 0.0,
        "Digit7" | "KeyU" | "KeyJ" | "KeyM" | "F7" => 0.08,
        "Digit8" | "KeyI" | "KeyK" | "Comma" | "F8" => 0.16,
        "Digit9" | "KeyO" | "KeyL" | "Period" | "AltRight" | "F9" => 0.24,
        "Digit0" | "KeyP" | "Semicolon" | "Slash" | "MetaRight" | "F10" => 0.32,
        "Minus" | "Equal" | "BracketLeft" | "BracketRight" | "Quote" | "Backslash"
        | "Backspace" | "Enter" | "ShiftRight" | "ControlRight" | "F11" | "F12" => 0.38,
        "Insert" | "Delete" | "Home" | "End" | "PageUp" | "PageDown" | "ArrowLeft"
        | "ArrowDown" | "ArrowUp" | "ArrowRight" => 0.42,
        _ => 0.0,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keycode_roundtrip_and_categories() {
        for code in [1u16, 14, 15, 28, 30, 42, 57, 86, 103, 125] {
            let web = evdev_to_web_code(code);
            assert_ne!(web, "Unknown");
            assert_eq!(web_code_to_evdev(web), Some(code));
        }
        assert_eq!(categorize_web_code("Space"), KeyCategory::Space);
        assert_eq!(categorize_web_code("Enter"), KeyCategory::Enter);
        assert_eq!(categorize_web_code("ShiftLeft"), KeyCategory::Modifier);
        assert_eq!(categorize_web_code("KeyA"), KeyCategory::Normal);
        assert!(web_code_pan("KeyQ") < 0.0);
        assert!(web_code_pan("KeyP") > 0.0);
        assert_eq!(web_code_pan("Space"), 0.0);
    }
}
